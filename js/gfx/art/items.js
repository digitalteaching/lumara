// ---------- Rucksack ----------

// Leder von außen nach innen: Umriss, Licht oder Schatten, Leder, Naht, Leder, Kante, Schatten, Creme.
function leather(d, lit, stitch) {
  if (d < 1) return 'k';
  if (d < 2) return lit ? 'r' : 'o';
  if (d < 3) return 'o';
  if (d < 4) return stitch ? 'y' : 'o';
  if (d < 5) return 'o';
  if (d < 6) return 'b';
  if (d < 7) return 'y';
  return 'c';
}

// Rahmen für border-image (24 × 24, Scheiben zu 8 px): runde Ecken. Das Nahtmuster wiederholt sich
// alle 4 px, darum passen die Kanten beim Wiederholen nahtlos aneinander. Innen einfarbig Creme.
function frame() {
  const R = 6;
  return Array.from({ length: 24 }, (_, y) => Array.from({ length: 24 }, (_, x) => {
    const dx = Math.min(x + 0.5, 23.5 - x), dy = Math.min(y + 0.5, 23.5 - y);
    const corner = dx < R && dy < R;
    const d = corner ? R - Math.hypot(R - dx, R - dy) : Math.min(dx, dy);
    if (d < 0) return '.';
    const lit = Math.min(x, y) <= Math.min(23 - x, 23 - y);
    const along = dx < dy ? y : x;
    return leather(d, lit, corner || along % 4 < 2);
  }).join(''));
}

// Klappe (48 × 16): oben angenäht, unten runde Ecken, in der Mitte eine Lasche mit Schnalle.
function flapRows() {
  const R = 6, W = 48, B = 12;
  const g = Array.from({ length: 16 }, (_, y) => Array.from({ length: W }, (_, x) => {
    const bx = Math.min(x + 0.5, W - 0.5 - x), by = B - (y + 0.5);
    const corner = bx < R && by < R;
    const d = Math.min(corner ? R - Math.hypot(R - bx, R - by) : Math.min(bx, by), y + 0.5);
    if (d < 0) return '.';
    return leather(Math.min(d, 4.5), y < 3 || (bx < by && x < W / 2), corner || (bx < by ? y : x) % 4 < 2);
  }));
  const tab = [
    '..kkkkkkkk..',
    '.krrooooobk.',
    '.kroooooobk.',
    'kkhhHHHHhhkk',
    'khkkkkkkkkrk',
    'khkoyyyykkrk',
    'khkkkkkkkkrk',
    'kkrrhhhhrrkk',
    '.kobbbbbbbk.',
    '..kkkkkkkk..',
  ];
  tab.forEach((line, i) => [...line].forEach((ch, j) => { if (ch !== '.') g[6 + i][18 + j] = ch; }));
  return g.map(r => r.join(''));
}

const flap = flapRows();

